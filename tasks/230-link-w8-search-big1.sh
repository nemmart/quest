#!/bin/bash
# Task 230-link-w8-search-big1 -- meshsim updater_wip WORKER8: the host link's protocol on its own (updater_wip/link at ed5b8f88,
# updater-w8; updater_wip/planning/sessions/WORKER8/tasks/make_task.sh), item: search-big1.
#   campaign    the random runs: 16 slices at once, each a range of seeds for 30 minutes, 2 million cycles of traffic
#               and noise a seed, chains of 1, 2, 4 and 16; then the slices added up. Any failing seed is a FAIL.
#   long-noise  16 runs with bursts of noise up to 300 ms (3e8 cycles), on chains of 1 and 2.
#   searches    the searches of the shrunken model too large for a session's machine: six, three at a time.
#   search-bigN one of them alone (searches.sh bigN), with all the memory the task may use.
# From an embedded kit. Writes only results/230-link-w8-search-big1/. Scratch in /tmp, removed first and at the end. Safe to re-run.
set -u
cd "$(dirname "$0")/.."
REPO=$PWD; RES=$REPO/results/230-link-w8-search-big1; mkdir -p "$RES"
W=/tmp/link-w8-230-link-w8-search-big1; rm -rf "$W"; mkdir -p "$W"
sed -n '/^__KIT_BEGIN__$/,/^__KIT_END__$/p' "$0" | sed '1d;$d' | base64 -d > "$W/kit.tgz" || exit 2
GOT=$(sha256sum "$W/kit.tgz" | cut -d' ' -f1); echo "kit sha256 $GOT"
[ "$GOT" = "0c0f34f85db5d949e72b8f36ae32a8d66b6fe831acaf70081db73367c5711617" ] || { echo "kit sha256 mismatch (want 0c0f34f85db5d949e72b8f36ae32a8d66b6fe831acaf70081db73367c5711617)"; exit 2; }
tar -xzf "$W/kit.tgz" -C "$W" || exit 2
cd "$W/updater_wip/link" || exit 2
ITEM=search-big1; FAIL=0; T0=$(date +%s)
verdict() { echo "VERDICT $1: $2"; echo "$1 $2" >> "$RES/VERDICTS"; case $2 in PASS*) ;; *) FAIL=1;; esac; }
: > "$RES/VERDICTS"
{ echo "kit: meshsim ed5b8f88 (updater-w8), updater_wip/link"; echo "host $(hostname); $(nproc) CPUs"; g++ --version | head -1; free -g | sed -n 2p; } | tee "$RES/machine.txt"
make -j8 all > "$RES/build.log" 2>&1 && build/test_header > "$RES/test_header.txt" 2>&1 && build/linkcase cases/*.case > "$RES/cases.txt" 2>&1
if [ $? = 0 ]; then verdict build PASS; else verdict build FAIL; rm -rf "$W"; exit 1; fi
case $ITEM in
campaign)
    for k in $(seq 0 15); do
        a=$((100000 + k * 10000))
        build/linkrun --seeds $a $((a + 9999)) --cycles 2000000 --seconds 1800 > "$RES/slice-$k.txt" 2>&1 &
    done
    wait
    python3 sum_runs.py "$RES"/slice-*.txt > "$RES/campaign.txt" 2>&1 && verdict campaign PASS || verdict campaign "FAIL (a seed failed: campaign.txt)"
    head -4 "$RES/campaign.txt"
    ;;
long-noise)
    for k in $(seq 1 10); do build/linkrun --seed $((200 + k)) --nodes 1 --cycles 1500000000 --long-noise -v > "$RES/long-$k.txt" 2>&1 & done
    for k in $(seq 11 16); do build/linkrun --seed $((200 + k)) --nodes 2 --cycles 700000000 --long-noise -v > "$RES/long-$k.txt" 2>&1 & done
    wait
    python3 sum_runs.py "$RES"/long-*.txt > "$RES/long-noise.txt" 2>&1 && verdict long-noise PASS || verdict long-noise "FAIL (long-noise.txt)"
    head -4 "$RES/long-noise.txt"
    ;;
searches)
    # Three at a time, each under 5 GB of address space: one that outgrows it stops alone, and its line says so.
    for set in "big5 big6 big7" "big8 big9 big10"; do
        for l in $set; do ( ulimit -v 5000000; MAX=20000000 ./searches.sh $l > "$RES/search-$l.txt" 2>&1 ) & done
        wait
    done
    cat "$RES"/search-*.txt | tee "$RES/searches.txt"
    if grep -q 'FAILS\|NO RESULT' "$RES/searches.txt"; then verdict searches "FAIL (searches.txt)"; else verdict searches "PASS ($(grep -c 'NOT complete' "$RES/searches.txt") not complete)"; fi
    ;;
search-big*)
    # One search with the memory there is: the task's own limit if it has one, else what the machine has free. The
    # search stops by itself at the states that fit (about 480 bytes a state here), and its line then says NOT complete.
    L=${ITEM#search-}
    LIM=$(cat "/sys/fs/cgroup$(cut -d: -f3 /proc/self/cgroup | head -1)/memory.max" 2>/dev/null || echo max)
    FREE=$(awk '/MemAvailable/ {print $2 * 1024}' /proc/meminfo)
    if [ "$LIM" = max ] || [ "$LIM" -gt "$FREE" ]; then LIM=$FREE; fi
    MAX=$((LIM / 10 * 8 / 480))
    echo "memory for the search: $LIM bytes; at most $MAX states" | tee -a "$RES/machine.txt"
    ( ulimit -v $((LIM / 1024 / 10 * 9)); MAX=$MAX SECS=2280 ./searches.sh "$L" > "$RES/search-$L.txt" 2>&1 )     # 38 minutes of the 45
    cat "$RES/search-$L.txt"
    if grep -q 'FAILS\|NO RESULT' "$RES/search-$L.txt"; then verdict search "FAIL (search-$L.txt)"
    elif grep -q 'NOT complete' "$RES/search-$L.txt"; then verdict search "PASS (not complete: no failure in the states tried)"
    else verdict search PASS; fi
    ;;
esac
echo "took $(( $(date +%s) - T0 )) s" | tee "$RES/TIMES"
cd /; rm -rf "$W"
exit $FAIL
