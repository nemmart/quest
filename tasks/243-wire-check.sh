#!/bin/bash
# Task 243-wire-check -- meshsim's wire between processes (updater_wip/wire/ at 670c84b2, updater-w10; updater_wip/wire/tests/make_task.sh).
# Steps: build matrix long stopping plants sanitize bench (REPEATS=5, ROUNDS=5). The wire joins the chain's processes (driver, ASICs) by shared memory
# with a sync every window; these runs check that the processes give exactly what a one-process reference gives, every
# byte at every end in every cycle, under load, pinned to one core and with random pauses; that stopping never hangs
# and leaves nothing behind; that planted bugs are caught; the sanitizers; and the cost (updater_wip/planning/sessions/
# WORKER10). From an embedded kit. Writes only results/243-wire-check/. Scratch in /tmp, removed first and at the end.
set -u
cd "$(dirname "$0")/.."
REPO=$PWD; RES=$REPO/results/243-wire-check; mkdir -p "$RES"
W=/tmp/wire-243-wire-check; rm -rf "$W"; mkdir -p "$W"
sed -n '/^__KIT_BEGIN__$/,/^__KIT_END__$/p' "$0" | sed '1d;$d' | base64 -d > "$W/kit.tgz" || exit 2
GOT=$(sha256sum "$W/kit.tgz" | cut -d' ' -f1); echo "kit sha256 $GOT"
[ "$GOT" = "233344c10130e8d055fe0a1ac0705c159d4a35b4e0ef9d0fb6e52e6c4064f9aa" ] || { echo "kit sha256 mismatch (want 233344c10130e8d055fe0a1ac0705c159d4a35b4e0ef9d0fb6e52e6c4064f9aa)"; exit 2; }
tar -xzf "$W/kit.tgz" -C "$W" || exit 2; rm -f "$W/kit.tgz"
(cd "$W/kit" && sha256sum -c --quiet HASHES) || { echo "kit files differ from HASHES"; exit 2; }
{ echo "kit: $(cat "$W/kit/VERSION")"; echo "host $(hostname); $(nproc) CPUs; $(uname -sr)"
  g++ --version 2>&1 | head -1; clang++ --version 2>&1 | head -1; gdb --version 2>&1 | head -1; free -g | sed -n 2p
} | tee "$RES/machine.txt"
T0=$(date +%s)
cd "$W/kit/updater_wip/wire"
REPEATS=5 ROUNDS=5 bash tests/run_checks.sh "$RES/logs" build matrix long stopping plants sanitize bench; rc=$?
cp "$RES/logs/summary.txt" "$RES/SUMMARY.txt"
echo "total $(( $(date +%s) - T0 )) s on $(nproc) CPUs" | tee -a "$RES/SUMMARY.txt"
if [ $rc = 0 ]; then echo "VERDICT wire-check: PASS" | tee "$RES/VERDICTS"; else echo "VERDICT wire-check: FAIL" | tee "$RES/VERDICTS"; fi
cd "$REPO"; rm -rf "$W"
exit $rc
