#!/bin/bash
# Task 067 -- mesh-sorter: rerun of 066 (meshsim v1.1 full-size suites). 066 failed only because runner.tgz
# left out meshsim/data/ (three 64x64 count matrices the all-to-all suites read: one99, trace, zipfraw).
# This task restores them from the small archive embedded below (15 KB, sha-checked), then runs
# runner/suites/run_suites.sh -j 4. Input: /tmp/runner.tgz (unchanged, sha-checked). Commits only VERDICT.txt
# and the last 30 lines of each suite's log; full logs stay in /tmp/ms-067/out. Expected 10-15 min.
set -u
cd "$(dirname "$0")/.."
RES=$PWD/results/067-meshsorter-suites-full; mkdir -p "$RES"
SRC=/tmp/runner.tgz
WANT=e0e646e76c5862a4cf36b8ab6271defec834307d2a8ffb575254eab3514fa533
DATA_WANT=295b68e3dd5504f2c6ddbd6b3c44ffe9a68c40a7c642cd97b8e064ae03accc16
[ -f "$SRC" ] || { echo "missing $SRC"; exit 2; }
GOT=$(sha256sum "$SRC" | cut -d' ' -f1); echo "runner.tgz sha256 $GOT"
[ "$GOT" = "$WANT" ] || { echo "sha256 mismatch (want $WANT)"; exit 2; }
W=/tmp/ms-067; rm -rf "$W"; mkdir -p "$W"
tar -xzf "$SRC" -C "$W" || exit 2
sed -n '/^__MSDATA_BEGIN__$/,/^__MSDATA_END__$/p' "$0" | sed '1d;$d' | base64 -d > "$W/msdata.tgz" || exit 2
DGOT=$(sha256sum "$W/msdata.tgz" | cut -d' ' -f1); echo "data sha256 $DGOT"
[ "$DGOT" = "$DATA_WANT" ] || { echo "embedded data sha256 mismatch"; exit 2; }
tar -xzf "$W/msdata.tgz" -C "$W/runner/suites/meshsim" || exit 2
ls -l "$W/runner/suites/meshsim/data"
cd "$W/runner/suites" || exit 2
echo "start $(date -u) on $(hostname), $(nproc) threads"; java -version 2>&1 | head -1
./run_suites.sh -j 4 "$W/out"; RC=$?
echo "run_suites.sh exit $RC at $(date -u)"
cp "$W/out/VERDICT.txt" "$RES/" 2>/dev/null
mkdir -p "$RES/tails"
for f in "$W"/out/*.log; do [ -f "$f" ] && tail -30 "$f" > "$RES/tails/$(basename "$f")"; done
cat "$W/out/VERDICT.txt" 2>/dev/null
exit $RC
